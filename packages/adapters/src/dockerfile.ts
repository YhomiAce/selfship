import { DEFAULT_NODE_VERSION, type PackageManager } from '@selfship/shared';
import type { BuildConfig } from './types';

/** Thrown when settings can't be safely written into a Dockerfile. */
export class UnsafeBuildConfigError extends Error {
  override name = 'UnsafeBuildConfigError';
}

/** Header added to every generated Dockerfile. */
export function header(adapter: string): string {
  return [
    `# Generated by Selfship (${adapter} adapter).`,
    '# To customise the build, commit your own Dockerfile to the repository.',
  ].join('\n');
}

/**
 * Re-checks a command right before it goes into a Dockerfile. The API
 * validates settings already; this is a second line of defence, because a
 * newline here would let a value inject extra Dockerfile instructions.
 *
 * @param command - Command to embed
 * @param label - Field name for the error message
 * @returns The command, unchanged
 * @throws {UnsafeBuildConfigError} If it contains line breaks or NUL bytes
 */
export function safeCommand(command: string, label: string): string {
  if (/[\r\n\0]/.test(command) || command.trim() === '') {
    throw new UnsafeBuildConfigError(`${label} must be a single, non-empty line`);
  }
  return command.trim();
}

/**
 * Re-checks a relative path (output directory) before embedding it.
 *
 * @param path - Path relative to the project root ('' = root)
 * @returns `.` for the root, otherwise the path
 * @throws {UnsafeBuildConfigError} For absolute paths, `..` or unusual characters
 */
export function safePath(path: string): string {
  if (path === '') return '.';
  if (!/^[\w.@-]+(\/[\w.@-]+)*$/.test(path) || path.split('/').includes('..')) {
    throw new UnsafeBuildConfigError(`Invalid path: ${path}`);
  }
  return path;
}

/**
 * Renders `ARG` lines for build-time environment variables. Docker exposes
 * build args as environment variables to `RUN` steps, so frameworks see them
 * during the build (e.g. `NEXT_PUBLIC_*`, `VITE_*`).
 *
 * @param names - Variable names
 * @returns Dockerfile lines (empty string when there are none)
 * @throws {UnsafeBuildConfigError} For names that aren't valid env var names
 */
export function buildArgs(names: readonly string[]): string {
  for (const name of names) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
      throw new UnsafeBuildConfigError(`Invalid build variable name: ${name}`);
    }
  }
  return names.map((name) => `ARG ${name}`).join('\n');
}

/**
 * Validates the container port.
 *
 * @param port - Port number
 * @returns The port
 * @throws {UnsafeBuildConfigError} If not an integer between 1 and 65535
 */
export function safePort(port: number): number {
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new UnsafeBuildConfigError(`Invalid port: ${port}`);
  }
  return port;
}

/** Files copied before `install`, for layer caching (per package manager). */
const MANIFESTS: Record<PackageManager, string | null> = {
  npm: 'package.json package-lock.json* npm-shrinkwrap.json* .npmrc*',
  pnpm: 'package.json pnpm-lock.yaml* .npmrc*',
  yarn: 'package.json yarn.lock* .npmrc* .yarnrc*',
  // Berry (.yarn/ folder) and bun need more than single files; copy everything.
  'yarn-berry': null,
  bun: null,
};

/**
 * Installs the openssl tool. Alpine ships libssl but not the binary, which
 * Prisma (one of the most common Node dependencies) uses to pick its engine;
 * without it Prisma loads an engine for OpenSSL 1.1 and every query fails.
 */
export const OPENSSL = 'RUN apk add --no-cache openssl';

/** Setup step for package managers that aren't bundled with Node. */
function packageManagerSetup(pm: PackageManager): string | null {
  if (pm === 'pnpm' || pm === 'yarn' || pm === 'yarn-berry') return 'RUN corepack enable';
  if (pm === 'bun') return 'RUN npm install --global bun';
  return null;
}

/**
 * Renders the shared "build" stage for JavaScript projects: install
 * dependencies (cached by manifest files where possible), copy the source,
 * expose build args and run the build command.
 *
 * @param config - Build settings
 * @param stageName - Name of the stage, referenced by later stages
 * @returns Dockerfile lines for the stage
 * @throws {UnsafeBuildConfigError} On unsafe settings
 */
export function nodeBuildStage(config: BuildConfig, stageName = 'build'): string {
  const { settings } = config;
  const pm = config.packageManager ?? 'npm';
  const node = settings.nodeVersion ?? DEFAULT_NODE_VERSION;
  const manifests = MANIFESTS[pm];
  const args = buildArgs(config.buildArgNames);

  const lines = [
    `FROM node:${node}-alpine AS ${stageName}`,
    'WORKDIR /app',
    OPENSSL,
    // Defaults as ARGs, not ENV: Docker lets ENV override a build arg of the
    // same name, which would ignore a user's CI=false (needed by old Create
    // React App builds that treat warnings as errors when CI=true).
    'ARG CI=true',
    'ARG NEXT_TELEMETRY_DISABLED=1',
    packageManagerSetup(pm),
    manifests ? `COPY ${manifests} ./` : 'COPY . .',
    settings.installCommand
      ? `RUN ${safeCommand(settings.installCommand, 'Install command')}`
      : null,
    manifests ? 'COPY . .' : null,
    args || null,
    settings.buildCommand ? `RUN ${safeCommand(settings.buildCommand, 'Build command')}` : null,
  ];
  return lines.filter((line): line is string => line !== null).join('\n');
}

